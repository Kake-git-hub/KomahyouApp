/** 下書きの localStorage キー接頭辞。教室別・版別に分ける(他教室の下書きが混ざらない)。 */
export const VERIFICATION_CHECKLIST_STORAGE_PREFIX = 'verification-checklist'
/** 折りたたみ状態のキー(教室をまたいで共通)。 */
export const VERIFICATION_CHECKLIST_COLLAPSED_STORAGE_KEY = `${VERIFICATION_CHECKLIST_STORAGE_PREFIX}:collapsed`

export function verificationChecklistStorageKey(
  classroomId: string | null | undefined,
  version: string = VERIFICATION_CHECKLIST.version,
): string {
  return `${VERIFICATION_CHECKLIST_STORAGE_PREFIX}:${classroomId ?? 'unknown'}:${version}`
}

/**
 * 同じ教室の**別の版**の下書きキーを列挙する(純関数・消すのは呼び出し側)。画像つきの下書きは 1 版で数 MB になり、
 * 版が上がるたびに残すと localStorage(約 5MB)が溢れて、下書きだけでなく盤面と日程表タブの排他など同じ origin の保存が
 * 黙って効かなくなる(regression-reviewer 指摘 2026-10-14)。版が上がった下書きはパネルから見えないので消してよい。
 * 他の教室の下書き・折りたたみ・別タブの拡大率のキーは触らない。
 */
export function collectStaleVerificationChecklistDraftKeys(
  keys: readonly string[],
  classroomId: string | null | undefined,
  version: string = VERIFICATION_CHECKLIST.version,
): string[] {
  const prefix = `${VERIFICATION_CHECKLIST_STORAGE_PREFIX}:${classroomId ?? 'unknown'}:`
  const current = verificationChecklistStorageKey(classroomId, version)
  return keys.filter((key) => key.startsWith(prefix) && key !== current && /^v\d+\.\d+\.\d+$/u.test(key.slice(prefix.length)))
}

export function createEmptyVerificationChecklistDraft(
  version: string = VERIFICATION_CHECKLIST.version,
): VerificationChecklistDraft {
  return { version, entries: {}, otherNotes: '', attachments: [], sent: {} }
}

function normalizeStatus(raw: unknown): VerificationChecklistStatus {
  return typeof raw === 'string' && (VERIFICATION_CHECKLIST_STATUSES as readonly string[]).includes(raw)
    ? (raw as VerificationChecklistStatus)
    : 'unchecked'
}

export function serializeVerificationChecklistDraft(draft: VerificationChecklistDraft): string {
  return JSON.stringify({
    version: draft.version,
    entries: draft.entries,
    otherNotes: draft.otherNotes,
    attachments: draft.attachments,
    sent: draft.sent,
  })
}

/** 保存値の添付 1 件を検証する(壊れていれば null・data URL は形とバイト数を検証)。 */
function normalizeStoredAttachment(raw: unknown): VerificationChecklistAttachment | null {
  if (!raw || typeof raw !== 'object' || Array.isArray(raw)) return null
  const candidate = raw as { id?: unknown; itemId?: unknown; name?: unknown; dataUrl?: unknown }
  if (typeof candidate.id !== 'string' || !candidate.id.trim()) return null
  if (typeof candidate.itemId !== 'string' || !candidate.itemId.trim()) return null
  const parsed = parseImageDataUrl(candidate.dataUrl)
  if (!parsed || parsed.byteLength > VERIFICATION_CHECKLIST_ATTACHMENT_MAX_BYTES) return null
  return {
    id: candidate.id,
    itemId: candidate.itemId,
    name: typeof candidate.name === 'string' && candidate.name.trim() ? candidate.name : 'image',
    mimeType: parsed.mimeType,
    dataUrl: candidate.dataUrl as string,
    byteLength: parsed.byteLength,
  }
}

/**
 * 保存済み文字列を下書きへ戻す。壊れた JSON・別版・想定外の形はすべて空の下書きとして扱う
 * (下書きが壊れてもパネルが落ちない・本番データには一切影響しない)。
 */
export function parseVerificationChecklistDraft(
  raw: unknown,
  version: string = VERIFICATION_CHECKLIST.version,
): VerificationChecklistDraft {
  const empty = createEmptyVerificationChecklistDraft(version)
  if (typeof raw !== 'string' || !raw.trim()) return empty
  let parsed: unknown
  try {
    parsed = JSON.parse(raw)
  } catch {
    return empty
  }
  if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) return empty
  const candidate = parsed as { version?: unknown; entries?: unknown; otherNotes?: unknown; attachments?: unknown; sent?: unknown }
  if (typeof candidate.version === 'string' && candidate.version !== version) return empty
  const entries: Record<string, VerificationChecklistEntry> = {}
  if (candidate.entries && typeof candidate.entries === 'object' && !Array.isArray(candidate.entries)) {
    for (const [id, value] of Object.entries(candidate.entries as Record<string, unknown>)) {
      if (!value || typeof value !== 'object' || Array.isArray(value)) continue
      const entry = value as { status?: unknown; memo?: unknown }
      const status = normalizeStatus(entry.status)
      const memo = typeof entry.memo === 'string' ? entry.memo : ''
      if (status === 'unchecked' && !memo) continue
      entries[id] = { status, memo }
    }
  }
  const attachments: VerificationChecklistAttachment[] = []
  if (Array.isArray(candidate.attachments)) {
    const seen = new Set<string>()
    for (const raw of candidate.attachments) {
      const attachment = normalizeStoredAttachment(raw)
      if (!attachment || seen.has(attachment.id)) continue
      seen.add(attachment.id)
      attachments.push(attachment)
    }
  }
  const sent: Record<string, VerificationChecklistSentRecord> = {}
  if (candidate.sent && typeof candidate.sent === 'object' && !Array.isArray(candidate.sent)) {
    for (const [id, value] of Object.entries(candidate.sent as Record<string, unknown>)) {
      if (!value || typeof value !== 'object' || Array.isArray(value)) continue
      const record = value as { status?: unknown; memo?: unknown; attachmentCount?: unknown; sentAt?: unknown; reportId?: unknown }
      const status = normalizeStatus(record.status)
      if (status === 'unchecked') continue
      sent[id] = {
        status,
        memo: typeof record.memo === 'string' ? record.memo : '',
        attachmentCount: typeof record.attachmentCount === 'number' && Number.isFinite(record.attachmentCount) && record.attachmentCount > 0 ? Math.floor(record.attachmentCount) : 0,
        sentAt: typeof record.sentAt === 'string' ? record.sentAt : '',
        reportId: typeof record.reportId === 'string' ? record.reportId : '',
      }
    }
  }
  return {
    version,
    entries,
    otherNotes: typeof candidate.otherNotes === 'string' ? candidate.otherNotes : '',
    attachments,
    sent,
  }
}

/**
 * 書き換えた項目(reworkedAt)の、書き換えより前に送った下書きを消す(純関数・2026-11-03 オーナー指示)。
 * 消すのは結果・メモ・その項目の画像・送った記録。書き換え後に送り直した項目(sentAt が reworkedAt 以後)と、
 * まだ送っていない下書きは触らない(送り直した後に開き直しても消えない)。変化が無ければ同じ下書きを返す。
 */
export function clearReworkedVerificationChecklistEntries(
  draft: VerificationChecklistDraft,
  items: readonly VerificationChecklistItem[] = VERIFICATION_CHECKLIST.items,
): VerificationChecklistDraft {
  const staleIds = new Set<string>()
  for (const item of items) {
    if (!item.reworkedAt) continue
    const sent = draft.sent[item.id]
    if (!sent) continue
    const sentTime = Date.parse(sent.sentAt)
    const reworkedTime = Date.parse(item.reworkedAt)
    if (Number.isFinite(sentTime) && Number.isFinite(reworkedTime) && sentTime >= reworkedTime) continue
    staleIds.add(item.id)
  }
  if (staleIds.size === 0) return draft
  const entries = { ...draft.entries }
  const sent = { ...draft.sent }
  for (const id of staleIds) {
    delete entries[id]
    delete sent[id]
  }
  return { ...draft, entries, sent, attachments: draft.attachments.filter((attachment) => !staleIds.has(attachment.itemId)) }
}

/** 1項目を書き換えた新しい下書きを返す(純関数・元は変えない)。 */
export function setVerificationChecklistEntry(
  draft: VerificationChecklistDraft,
  id: string,
  patch: Partial<VerificationChecklistEntry>,
): VerificationChecklistDraft {
  const current = draft.entries[id] ?? { status: 'unchecked' as VerificationChecklistStatus, memo: '' }
  const next: VerificationChecklistEntry = {
    status: patch.status ?? current.status,
    memo: patch.memo ?? current.memo,
  }
  return { ...draft, entries: { ...draft.entries, [id]: next } }
}

/**
 * メモ欄の入力を反映する(純関数)。メモ欄は結果に関わらず常に出すので、**未確認のままメモを書いたら要改善に切り替える**
 * (未確認の行は送信本文に載らない＝書いたメモが黙って捨てられるのを防ぐ・2026-09-13)。OK/要改善はそのまま。
 */
export function setVerificationChecklistMemo(
  draft: VerificationChecklistDraft,
  id: string,
  memo: string,
): VerificationChecklistDraft {
  const current = getVerificationChecklistEntry(draft, id)
  const status: VerificationChecklistStatus = current.status === 'unchecked' && memo.trim() ? 'needs-fix' : current.status
  return setVerificationChecklistEntry(draft, id, { status, memo })
}

export function setVerificationChecklistOtherNotes(
  draft: VerificationChecklistDraft,
  otherNotes: string,
): VerificationChecklistDraft {
  return { ...draft, otherNotes }
}

export function getVerificationChecklistEntry(
  draft: VerificationChecklistDraft,
  id: string,
): VerificationChecklistEntry {
  return draft.entries[id] ?? { status: 'unchecked', memo: '' }
}

/** 項目の添付画像(下書き内の順)。 */
export function getVerificationChecklistAttachments(draft: VerificationChecklistDraft, itemId: string): VerificationChecklistAttachment[] {
  return draft.attachments.filter((attachment) => attachment.itemId === itemId)
}

export function sumVerificationChecklistAttachmentBytes(draft: VerificationChecklistDraft): number {
  return draft.attachments.reduce((total, attachment) => total + attachment.byteLength, 0)
}

export type VerificationChecklistAttachmentInput = {
  itemId: string
  name: string
  /** `data:image/(jpeg|png|webp);base64,…`(画面側で縮めた後のもの)。 */
  dataUrl: string
}

/**
 * 項目に画像を 1 枚足す(純関数)。断る理由があれば error を返し下書きは変えない:
 * 形が画像の data URL でない／1 枚の上限超え／項目の枚数上限／下書き全体の合計上限。
 * **未確認のまま画像だけ付けたら要改善に切り替える**(メモと同じ理由＝未確認の行は送信本文に載らず、画像が黙って捨てられる)。
 */
export function addVerificationChecklistAttachment(
  draft: VerificationChecklistDraft,
  input: VerificationChecklistAttachmentInput,
  id: string,
): { draft: VerificationChecklistDraft; error: string | null } {
  const parsed = parseImageDataUrl(input.dataUrl)
  if (!parsed) return { draft, error: '画像(JPEG / PNG / WebP)として読めませんでした。' }
  if (parsed.byteLength > VERIFICATION_CHECKLIST_ATTACHMENT_MAX_BYTES) {
    return { draft, error: `画像が大きすぎます(上限 ${Math.round(VERIFICATION_CHECKLIST_ATTACHMENT_MAX_BYTES / 100_000) / 10}MB)。` }
  }
  if (getVerificationChecklistAttachments(draft, input.itemId).length >= VERIFICATION_CHECKLIST_ATTACHMENT_MAX_PER_ITEM) {
    return { draft, error: `この項目に付けられる画像は ${VERIFICATION_CHECKLIST_ATTACHMENT_MAX_PER_ITEM} 枚までです。` }
  }
  if (draft.attachments.length >= VERIFICATION_CHECKLIST_ATTACHMENT_MAX_TOTAL) {
    return { draft, error: `下書きに置ける画像は全部で ${VERIFICATION_CHECKLIST_ATTACHMENT_MAX_TOTAL} 枚までです。画像を付けた項目を先に送信してください(送った画像は下書きから外れます)。` }
  }
  if (sumVerificationChecklistAttachmentBytes(draft) + parsed.byteLength > VERIFICATION_CHECKLIST_ATTACHMENT_TOTAL_MAX_BYTES) {
    return { draft, error: '画像の合計が上限を超えます。先に送信するか、ほかの画像を外してください。' }
  }
  if (draft.attachments.some((attachment) => attachment.id === id)) return { draft, error: '同じ画像が既に付いています。' }
  const attachment: VerificationChecklistAttachment = {
    id,
    itemId: input.itemId,
    name: input.name.trim() || 'image',
    mimeType: parsed.mimeType,
    dataUrl: input.dataUrl,
    byteLength: parsed.byteLength,
  }
  const current = getVerificationChecklistEntry(draft, input.itemId)
  const status: VerificationChecklistStatus = current.status === 'unchecked' ? 'needs-fix' : current.status
  const next = setVerificationChecklistEntry(draft, input.itemId, { status })
  return { draft: { ...next, attachments: [...next.attachments, attachment] }, error: null }
}

/** 画像を 1 枚外す(純関数)。無い id なら同じ内容の下書きを返す。 */
export function removeVerificationChecklistAttachment(draft: VerificationChecklistDraft, attachmentId: string): VerificationChecklistDraft {
  if (!draft.attachments.some((attachment) => attachment.id === attachmentId)) return draft
  return { ...draft, attachments: draft.attachments.filter((attachment) => attachment.id !== attachmentId) }
}

/**
 * 送信に同梱する添付(項目の並び順・label=項目 id)。未確認の項目の画像は送らない(本文に載らない項目と揃える＝
 * ただし addVerificationChecklistAttachment が未確認→要改善に切り替えるので、普通は全部送られる)。
 */
export function buildVerificationChecklistReportAttachments(
  draft: VerificationChecklistDraft,
  items: readonly VerificationChecklistItem[] = VERIFICATION_CHECKLIST.items,
): DeveloperReportAttachment[] {
  const result: DeveloperReportAttachment[] = []
  for (const item of items) {
    if (getVerificationChecklistEntry(draft, item.id).status === 'unchecked') continue
    for (const attachment of getVerificationChecklistAttachments(draft, item.id)) {
      result.push({ label: item.id, name: attachment.name, mimeType: attachment.mimeType, dataUrl: attachment.dataUrl })
    }
  }
  return result
}

/** 送信本文・Markdown に添える画像枚数の印(`[画像2枚]`)。無ければ空文字。 */
export function formatVerificationChecklistAttachmentMark(count: number): string {
  return count > 0 ? `[画像${count}枚]` : ''
}

export type VerificationChecklistProgress = {
  total: number
  checked: number
  ok: number
  needsFix: number
  remaining: number
  /** 結果を付けたがまだ送っていない(送った後に変えた分も含む)項目の数(2026-11-03)。 */
  unsent: number
}

/** 進捗カウント(折りたたみボタンの「確認リスト n/N」用)。 */
export function countVerificationChecklistProgress(
  draft: VerificationChecklistDraft,
  items: readonly VerificationChecklistItem[] = VERIFICATION_CHECKLIST.items,
): VerificationChecklistProgress {
  let ok = 0
  let needsFix = 0
  let unsent = 0
  for (const item of items) {
    const status = getVerificationChecklistEntry(draft, item.id).status
    if (status === 'ok') ok += 1
    else if (status === 'needs-fix') needsFix += 1
    const sendState = resolveVerificationChecklistItemSendState(draft, item.id)
    if (sendState === 'unsent' || sendState === 'changed') unsent += 1
  }
  const checked = ok + needsFix
  return { total: items.length, checked, ok, needsFix, remaining: items.length - checked, unsent }
}

/** 送信本文の先頭に必ず付く目印。開発者が受信メールで確認リストだと判別できるようにする。 */
export function buildVerificationChecklistMarker(version: string = VERIFICATION_CHECKLIST.version): string {
  return `[確認リスト ${version}]`
}

function singleLineMemo(memo: string): string {
  return memo.replace(/\r\n?/gu, '\n').split('\n').map((line) => line.trim()).filter(Boolean).join(' / ')
}

/** 送信本文の明細行(未確認は省略)。生徒名などは載せない＝項目 id とメモだけ。 */
function buildVerificationChecklistLines(
  draft: VerificationChecklistDraft,
  items: readonly VerificationChecklistItem[],
): string[] {
  const lines: string[] = []
  for (const item of items) {
    const entry = getVerificationChecklistEntry(draft, item.id)
    if (entry.status === 'unchecked') continue
    const memo = singleLineMemo(entry.memo)
    // 画像の枚数はメモの末尾に印として残す(画像本体は添付として別に届く・読み取りツールは印を無視してもメモが読める)。
    const mark = formatVerificationChecklistAttachmentMark(getVerificationChecklistAttachments(draft, item.id).length)
    const tail = [memo, mark].filter(Boolean).join(' ')
    if (entry.status === 'ok') lines.push(tail ? `- ${item.id} OK: ${tail}` : `- ${item.id} OK`)
    else lines.push(tail ? `- ${item.id} 要改善: ${tail}` : `- ${item.id} 要改善`)
  }
  const other = singleLineMemo(draft.otherNotes)
  if (other) lines.push(`- その他: ${other}`)
  return lines
}

function packLines(lines: string[], header: string, limit: number): string[] {
  const budget = limit - header.length - 1
  const parts: string[] = []
  let buffer: string[] = []
  let used = 0
  for (const rawLine of lines) {
    // 1行だけで上限を超える長文メモは、その行を切って必ず収める(送信不能にしない)。
    const line = rawLine.length > budget ? `${rawLine.slice(0, Math.max(0, budget - 1))}…` : rawLine
    const cost = buffer.length === 0 ? line.length : line.length + 1
    if (buffer.length > 0 && used + cost > budget) {
      parts.push(buffer.join('\n'))
      buffer = [line]
      used = line.length
      continue
    }
    buffer.push(line)
    used += cost
  }
  if (buffer.length > 0) parts.push(buffer.join('\n'))
  return parts
}

/**
 * 確認リストを「要望・報告」の本文(複数通)に整形する。
 *  - 先頭行は必ず目印 `[確認リスト <版>]`(分割時は `(1/2)` 等を付ける)。
 *  - 未確認の項目は省略。何も確認していなければ空配列を返す(= 送らない)。
 *  - 1通が DEVELOPER_REPORT_NOTE_LIMIT(2000字)を超えないように分割する。
 */
export function buildVerificationChecklistReportNotes(
  draft: VerificationChecklistDraft,
  options?: { items?: readonly VerificationChecklistItem[]; limit?: number },
): string[] {
  const items = options?.items ?? VERIFICATION_CHECKLIST.items
  const limit = options?.limit ?? DEVELOPER_REPORT_NOTE_LIMIT
  const lines = buildVerificationChecklistLines(draft, items)
  if (lines.length === 0) return []
  const marker = buildVerificationChecklistMarker(draft.version)

  const single = `${marker}\n${lines.join('\n')}`
  if (single.length <= limit) return [single]

  // 分割が必要。通数は「(i/n)」の桁数に依存するので、通数が安定するまで数回試す。
  let total = packLines(lines, `${marker} (1/9)`, limit).length
  for (let attempt = 0; attempt < 5; attempt += 1) {
    const header = `${marker} (1/${total})`
    const parts = packLines(lines, header, limit)
    if (parts.length === total) {
      return parts.map((body, index) => `${marker} (${index + 1}/${total})\n${body}`)
    }
    total = parts.length
  }
  const parts = packLines(lines, `${marker} (1/${total})`, limit)
  return parts.map((body, index) => `${marker} (${index + 1}/${parts.length})\n${body}`)
}

// ---- 項目ごとの送信(2026-11-03 オーナー指示「送信をまとめてではなく一件ごとに」) ----
//
// 1 項目 = 1 通。本文はまとめ送りと同じ書式(先頭マーカー＋結果行 1 行)なので、読み取り側(verificationChecklistResults.ts /
// tools の .mjs)はそのまま読める。1 通もの(total=1)は受付ごとに別扱いで集約される(mergeChecklistReports)。
// ★1 項目の本文は必ず 1 通に収める(分割すると別の項目の分割と取り違えるため)。長すぎるメモは末尾を「…」で切る。

/** 1 項目の送信状態。unchecked=結果がまだ無い / unsent=未送信 / sent=送信済み(その後の変更なし) / changed=送った後に変えた。 */
export type VerificationChecklistItemSendState = 'unchecked' | 'unsent' | 'sent' | 'changed'

export function resolveVerificationChecklistItemSendState(draft: VerificationChecklistDraft, itemId: string): VerificationChecklistItemSendState {
  const entry = getVerificationChecklistEntry(draft, itemId)
  if (entry.status === 'unchecked') return 'unchecked'
  const sent = draft.sent[itemId]
  if (!sent) return 'unsent'
  const pendingImages = getVerificationChecklistAttachments(draft, itemId).length
  return sent.status === entry.status && singleLineMemo(sent.memo) === singleLineMemo(entry.memo) && pendingImages === 0 ? 'sent' : 'changed'
}

/** 送信本文のマーカーと 1 行を、上限に収めて 1 通にする。 */
function buildSingleLineNote(version: string, line: string, limit: number): string {
  const marker = buildVerificationChecklistMarker(version)
  const budget = Math.max(1, limit - marker.length - 1)
  const body = line.length > budget ? `${line.slice(0, Math.max(0, budget - 1))}…` : line
  return `${marker}\n${body}`
}

/** 1 項目だけの送信本文(1 通)。未確認・一覧に無い項目なら null(= 送らない)。 */
export function buildVerificationChecklistItemReportNote(
  draft: VerificationChecklistDraft,
  itemId: string,
  options?: { items?: readonly VerificationChecklistItem[]; limit?: number },
): string | null {
  const items = options?.items ?? VERIFICATION_CHECKLIST.items
  const item = items.find((candidate) => candidate.id === itemId)
  if (!item) return null
  const [line] = buildVerificationChecklistLines({ ...draft, otherNotes: '' }, [item])
  if (!line) return null
  return buildSingleLineNote(draft.version, line, options?.limit ?? DEVELOPER_REPORT_NOTE_LIMIT)
}

/** フリーメモ(その他)だけの送信本文(1 通)。空なら null。 */
export function buildVerificationChecklistOtherNotesReportNote(
  draft: VerificationChecklistDraft,
  options?: { limit?: number },
): string | null {
  const other = singleLineMemo(draft.otherNotes)
  if (!other) return null
  return buildSingleLineNote(draft.version, `- その他: ${other}`, options?.limit ?? DEVELOPER_REPORT_NOTE_LIMIT)
}

/** 1 項目に添える画像(label=項目 id)。 */
export function buildVerificationChecklistItemReportAttachments(draft: VerificationChecklistDraft, itemId: string): DeveloperReportAttachment[] {
  if (getVerificationChecklistEntry(draft, itemId).status === 'unchecked') return []
  return getVerificationChecklistAttachments(draft, itemId).map((attachment) => ({ label: itemId, name: attachment.name, mimeType: attachment.mimeType, dataUrl: attachment.dataUrl }))
}

/**
 * 1 項目を送れたことを下書きへ記録する(純関数)。送った結果とメモを残し、送った画像は下書きから外す
 * (サーバーに届いた・localStorage の容量を空ける・もう一度送ったときに同じ画像を二重に送らない)。
 */
export function markVerificationChecklistItemSent(
  draft: VerificationChecklistDraft,
  itemId: string,
  receipt: { reportId: string; sentAt: string; attachmentCount: number },
): VerificationChecklistDraft {
  const entry = getVerificationChecklistEntry(draft, itemId)
  if (entry.status === 'unchecked') return draft
  return {
    ...draft,
    attachments: draft.attachments.filter((attachment) => attachment.itemId !== itemId),
    sent: {
      ...draft.sent,
      [itemId]: { status: entry.status, memo: entry.memo, attachmentCount: receipt.attachmentCount, sentAt: receipt.sentAt, reportId: receipt.reportId },
    },
  }
}

const STATUS_LABELS: Record<VerificationChecklistStatus, string> = {
  unchecked: '未確認',
  ok: 'OK',
  'needs-fix': '要改善',
}

export function verificationChecklistStatusLabel(status: VerificationChecklistStatus): string {
  return STATUS_LABELS[status]
}

/** クリップボード用の Markdown(送信できないときの保険)。未確認も含めて全項目を出す。 */
export function buildVerificationChecklistMarkdown(
  draft: VerificationChecklistDraft,
  items: readonly VerificationChecklistItem[] = VERIFICATION_CHECKLIST.items,
): string {
  const progress = countVerificationChecklistProgress(draft, items)
  const lines: string[] = [
    `# ${buildVerificationChecklistMarker(draft.version)}`,
    `確認 ${progress.checked}/${progress.total}(OK ${progress.ok} / 要改善 ${progress.needsFix})`,
    '',
  ]
  let currentArea = ''
  for (const item of items) {
    if (item.area !== currentArea) {
      currentArea = item.area
      lines.push(`## ${currentArea}`)
    }
    const entry = getVerificationChecklistEntry(draft, item.id)
    const box = entry.status === 'ok' ? 'x' : ' '
    lines.push(`- [${box}] ${item.id} ${item.title} — ${verificationChecklistStatusLabel(entry.status)}`)
    const memo = singleLineMemo(entry.memo)
    if (memo) lines.push(`  - メモ: ${memo}`)
    const attachments = getVerificationChecklistAttachments(draft, item.id)
    if (attachments.length > 0) lines.push(`  - 画像: ${attachments.length} 枚(${attachments.map((attachment) => attachment.name).join(', ')})`)
  }
  const other = singleLineMemo(draft.otherNotes)
  if (other) {
    lines.push('')
    lines.push('## その他の気づき')
    lines.push(`- ${other}`)
  }
  return lines.join('\n')
}
