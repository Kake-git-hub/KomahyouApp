/** 1項目の確認状態。未確認は送信対象から外す(省略)。 */
export const VERIFICATION_CHECKLIST_STATUSES = ['unchecked', 'ok', 'needs-fix'] as const
export type VerificationChecklistStatus = (typeof VERIFICATION_CHECKLIST_STATUSES)[number]

export type VerificationChecklistItem = {
  /** 送信本文に載る短い識別子。生徒名などの個人情報は含めない。 */
  id: string
  /** 画面上の分類見出し(盤面 / PDF / 日程表 …)。 */
  area: string
  title: string
  /** 前提(あれば1行)。どの状態で始めるか・何を選ぶか。オーナーの準備を最小にするため、できるだけ書かない。 */
  prep?: string
  /** 操作。1〜2手順に収める(オーナー指示 2026-09-17「手順が多すぎて大変」・テストで上限を固定)。 */
  steps: string[]
  /** 見るところ。操作のあと何を確かめるか(最大4つ)。 */
  check?: string[]
  /** この項目を追加した版(あとから「いつからの確認項目か」を追える)。 */
  introducedIn: string
}

/**
 * 文面の中の生徒の指し方(2026-10-10 オーナー指示「開発用教室は名前を見ていいので、確認リストに生徒名を表示して」)。
 * ソースには生徒名を書かず `{{student:<生徒ID>}}` と書き、画面側が開いている教室(開発用教室)の生徒データから名前を引いて差し込む。
 * 生徒 ID(s069 など)は個人情報ではないのでリポジトリに置ける。名前が引けない(別の教室・退塾で消えた等)ときは
 * 「名前不明(<生徒ID>)」にして、学年・科目だけで机を探せるようにする。
 */
export const VERIFICATION_CHECKLIST_STUDENT_PLACEHOLDER = /\{\{student:([A-Za-z0-9_-]+)\}\}/gu

/** 文面の生徒プレースホルダを名前へ置き換える(純関数)。resolver が null/空を返したら「名前不明(ID)」。 */
export function resolveVerificationChecklistText(text: string, resolveStudentName?: (studentId: string) => string | null | undefined): string {
  return text.replace(VERIFICATION_CHECKLIST_STUDENT_PLACEHOLDER, (_match, studentId: string) => {
    const name = resolveStudentName?.(studentId)?.trim()
    return name ? name : `名前不明(${studentId})`
  })
}

