/** 1項目の確認状態。未確認は送信対象から外す(省略)。 */
export const VERIFICATION_CHECKLIST_STATUSES = ['unchecked', 'ok', 'needs-fix'] as const
export type VerificationChecklistStatus = (typeof VERIFICATION_CHECKLIST_STATUSES)[number]

export type VerificationChecklistItem = {
  /** 送信本文に載る短い識別子。生徒名などの個人情報は含めない。 */
  id: string
  /** 画面上の分類見出し(盤面 / PDF / 日程表 …)。 */
  area: string
  title: string
  /**
   * 操作。3手順まで・短い言い切り(オーナー指示 2026-09-17「手順が多すぎて大変」・2026-11-07「文章が多すぎる」・テストで上限を固定)。
   * 準備も操作の手順の 1 つとして正しい順に入れる(第120版・2026-11-07 オーナー指示「準備する→操作 にこだわらず、操作の手順の一つとして、
   * 正しい手順で準備するを交えて。項目は 操作 → 確認 だけ」)。準備だけの欄は持たない。
   */
  steps: string[]
  /**
   * 確認(画面の見出しは「確認」)。操作のあと画面がどうなっていれば OK か(最大3つ・各行は「」の外で 40 字まで)。経緯や「詳細」の文は書かない
   * (オーナー指示 2026-11-07「詳細や結果は文章にする必要はない。盤面でどうなっていればよいかを簡潔に」)。
   */
  check?: string[]
  /** この項目を追加した版(あとから「いつからの確認項目か」を追える)。 */
  introducedIn: string
  /**
   * 要改善を受けて直し、項目を書き換えた時刻(ISO・2026-11-03 オーナー指示「対応したなら要改善の状態は外して、テキスト欄に前回のメモは
   * 残さなくていい」)。これより前に送った下書きの結果・メモ・画像・送った記録は、パネルを開いたときに消す
   * (clearReworkedVerificationChecklistEntries)。各教室の送信済みの結果(項目の上の欄)はサーバーの記録なので残る。
   * 書き換えたら、オーナーがその項目を送った後・デプロイ前の時刻を入れる。
   */
  reworkedAt?: string
  /**
   * 「準備する」ボタンを出す(2026-11-06 オーナー選択「案 C(段階導入)」・spec-developer-report §E-2-4)。開発用教室・テスト教室で、
   * 開いているコマ表に準備を自動で置く(置き方は src/components/schedule-board/checklistPrep.ts・id の一致はテストで固定)。
   * ボタンは「準備する」を押す手順の行に出す(findVerificationChecklistPrepStepIndex)。その手順は最初に置き「「準備する」を押して「保存」」と書く。
   */
  autoPrep?: true
}

/**
 * 「準備する」ボタンを出す手順の位置(純関数・第120版 2026-11-07)。autoPrep の項目で、最初に「「準備する」を押」で始まる手順。
 * 無ければ -1(ボタンを出さない)。「もう一度「準備する」→ …」のような 2 回目の手順にはボタンを出さない(最初の 1 つだけ)。
 */
export function findVerificationChecklistPrepStepIndex(item: Pick<VerificationChecklistItem, 'autoPrep' | 'steps'>): number {
  if (!item.autoPrep) return -1
  return item.steps.findIndex((step) => step.startsWith('「準備する」を押'))
}

/**
 * 文面の中の生徒の指し方(2026-10-10 オーナー指示「開発用教室は名前を見ていいので、確認リストに生徒名を表示して」)。
 * ソースには生徒名を書かず `{{student:<生徒ID>}}` と書き、画面側が開いている教室(開発用教室)の生徒データから名前を引いて差し込む。
 * 生徒 ID(s069 など)は個人情報ではないのでリポジトリに置ける。名前が引けない(別の教室・退塾で消えた等)ときは
 * 「名前不明(<生徒ID>)」にして、学年・科目だけで机を探せるようにする。
 */
export const VERIFICATION_CHECKLIST_STUDENT_PLACEHOLDER = /\{\{student:([A-Za-z0-9_-]+)\}\}/gu

/**
 * 「準備する」の結果の事実(第119版・2026-11-07 オーナー指示「など細かい事象説明は不要。今のシンプルにした文に、いつの誰を追記して。わかりにくいので。」)。
 * キー → 表示する文字列(例 slot=「2/2(火) 2限」・deskA=「机 2」・X=手で置いた講師の名前・A=確認用の生徒の名前)。準備(checklistPrep.ts / checklistPrepSequence.ts)が
 * 結果に載せ、パネル(VerificationChecklistPanel)がその項目の最後の準備結果の facts で項目の操作・確認の文の `{{prep:<キー>}}` を置き換える。画面だけ(下書き・送信本文には載せない)。
 */
export type ChecklistPrepFacts = Readonly<Record<string, string>>

/** 項目の文の中の準備の事実の指し方 `{{prep:<キー>}}`(操作・確認の文だけに書く・テストで固定)。 */
export const CHECKLIST_PREP_FACT_TOKEN = /\{\{prep:([A-Za-z0-9_-]+)\}\}/gu

/**
 * facts が無い(まだ押していない・再読み込みの後・失敗した)・キーが無いときに出す言葉。項目の文に使うキーは全部ここに置く(テストで固定)。
 * 机のキーは役割の言葉を文の側に書く(「テンプレの机({{prep:deskT}})」)。
 */
export const CHECKLIST_PREP_FACT_DEFAULTS: Readonly<Record<string, string>> = {
  slot: '準備したコマ',
  dayA: 'A',
  dayB: 'B',
  rFrom: '元の時限',
  desk1: '(1) の机',
  deskA: '机 A',
  deskB: '机 B',
  deskC: '机 C',
  deskK: '机 K',
  deskM: '机 M',
  deskP: '机 P',
  deskT: '机 T',
  X: '講師 X',
  Y: '講師 Y',
  W: '講師 W',
  A: '生徒 A',
  B: '生徒 B',
  C: '生徒 C',
  R: '生徒 R',
  trial: '体験',
}

/** 文の `{{prep:<キー>}}` を facts の値で置き換える(純関数)。値が無い・空ならキーの既定の言葉(既定も無ければキーそのもの)。 */
export function resolveChecklistPrepFactTokens(text: string, facts?: ChecklistPrepFacts | null): string {
  return text.replace(CHECKLIST_PREP_FACT_TOKEN, (_match, key: string) => {
    const value = facts?.[key]?.trim()
    return value ? value : (CHECKLIST_PREP_FACT_DEFAULTS[key] ?? key)
  })
}

/** 項目の文(題名・操作・確認)に使っている `{{prep:<キー>}}` のキー(出てきた順・重複なし)。 */
export function listChecklistPrepFactTokenKeys(item: Pick<VerificationChecklistItem, 'title' | 'steps' | 'check'>): string[] {
  const keys: string[] = []
  for (const line of [item.title, ...item.steps, ...(item.check ?? [])]) {
    for (const match of line.matchAll(CHECKLIST_PREP_FACT_TOKEN)) if (!keys.includes(match[1])) keys.push(match[1])
  }
  return keys
}

/**
 * 文面の生徒プレースホルダを名前へ置き換える(純関数)。resolver が null/空を返したら「名前不明(ID)」。
 * 第119版(2026-11-07): 準備の事実 `{{prep:<キー>}}` も同じ場所で一緒に置き換える(prepFacts が無ければ既定の言葉)。
 */
export function resolveVerificationChecklistText(text: string, resolveStudentName?: (studentId: string) => string | null | undefined, prepFacts?: ChecklistPrepFacts | null): string {
  const withStudents = text.replace(VERIFICATION_CHECKLIST_STUDENT_PLACEHOLDER, (_match, studentId: string) => {
    const name = resolveStudentName?.(studentId)?.trim()
    return name ? name : `名前不明(${studentId})`
  })
  return resolveChecklistPrepFactTokens(withStudents, prepFacts)
}

