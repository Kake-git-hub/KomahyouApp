/** テスト教室の確認リストを出す教室か(workspaceKey と classroomId の完全一致・純関数)。 */
export function isTestClassroomVerificationChecklistTarget(
  workspaceKey: string | null | undefined,
  classroomId: string | null | undefined,
): boolean {
  const ws = typeof workspaceKey === 'string' ? workspaceKey.trim() : ''
  const id = typeof classroomId === 'string' ? classroomId.trim() : ''
  if (!ws || !id) return false
  return ws === TEST_CLASSROOM_VERIFICATION_CHECKLIST_TARGET.workspaceKey && id === TEST_CLASSROOM_VERIFICATION_CHECKLIST_TARGET.classroomId
}

/**
 * 開いている教室に出す確認リストの定義を選ぶ(純関数)。テスト教室ならテスト教室の定義、それ以外(開発用教室)は従来の定義。
 * パネルを出すかどうかは App 側の isActingDevelopmentClassroom が決める(本番教室では呼ばれても使われない)。
 */
export function resolveVerificationChecklistDefinitionFor(
  workspaceKey: string | null | undefined,
  classroomId: string | null | undefined,
): VerificationChecklistDefinition {
  return isTestClassroomVerificationChecklistTarget(workspaceKey, classroomId) ? TEST_CLASSROOM_VERIFICATION_CHECKLIST : VERIFICATION_CHECKLIST
}

/** App 用: workspaceKey は現在の接続先(env VITE_FIREBASE_WORKSPACE_KEY)。ローカルモードでは空文字なので従来の定義になる。 */
export function resolveVerificationChecklistDefinition(
  classroomId: string | null | undefined,
  workspaceKey: string = getFirebaseBackendConfig().workspaceKey,
): VerificationChecklistDefinition {
  return resolveVerificationChecklistDefinitionFor(workspaceKey, classroomId)
}

/** テスト教室の登録台帳の行(テストが「台帳に載っている」ことを固定するために公開)。 */
export function findTestClassroomVerificationChecklistRegistryEntry() {
  return findDevelopmentClassroomEntry(TEST_CLASSROOM_VERIFICATION_CHECKLIST_TARGET.workspaceKey, TEST_CLASSROOM_VERIFICATION_CHECKLIST_TARGET.classroomId)
}
